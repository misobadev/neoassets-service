// ErrQuotaExceeded is returned when a subject has consumed its daily quota.
var ErrQuotaExceeded = errors.New("daily scrape quota exceeded")

// Default scrape limits, overridable from the environment.
const (
	// defaultRPMPerThread is the per-minute request budget granted per scrape
	// thread: the effective RPM is threads * RPMPerThread (guest 2 -> 200,
	// admin 16 -> 1600). Threads already scale the daily quota.
	defaultRPMPerThread = 100

	// maxGamesLimit is how many candidates a name search scans to pick the best
	// single match.
	maxGamesLimit = 25

	defaultPopularLimit = 20
	maxPopularLimit     = 50

	// maxDebugCallsPerDay caps developer debug requests per app per day.
	maxDebugCallsPerDay = 100

	// maxSystemsPerRequest caps how many systems a family/group selector may
	// expand to, bounding the cost of a single request.
	maxSystemsPerRequest = 50

	// maxScrapeNameLen caps the cleaned name sent to the search, bounding the
	// number of LIKE predicates generated by tokenization.
	maxScrapeNameLen = 200
)

// ScrapeService authenticates scraping API consumers, enforces per-minute rate
// limits and the daily scrape quota, and serves the public catalog payloads.
type ScrapeService struct {
	repo      *repository.Repository
	meta      *Service // catalog reads (systems/games) reused from the web service
	jwtSecret string

	guestThreads int
	rpmPerThread int
	debugEnabled bool
	requireVerified bool

	mu       sync.Mutex
	limiters map[string]*limiterEntry
}

// limiterEntry pairs a token bucket with its last access time so stale entries
// can be evicted instead of resetting the whole map. rpm is kept so a bucket is
// rebuilt when a subject's thread count changes.
type limiterEntry struct {
	lim  *rate.Limiter
	rpm  int
	last time.Time
}

// NewScrapeService creates a ScrapeService. Non-positive values fall back to
// the defaults. The daily quota is per account and scales with the thread count
// (threads * DailyGamesPerThread), so more threads also means a bigger daily
// limit.
func NewScrapeService(repo *repository.Repository, meta *Service, jwtSecret string, guestThreads, rpmPerThread int, debugEnabled, requireVerified bool) *ScrapeService {
	if guestThreads <= 0 {
		guestThreads = repository.GuestThreads
	}
	if rpmPerThread <= 0 {
		rpmPerThread = defaultRPMPerThread
	}
	return &ScrapeService{
		repo:            repo,
		meta:            meta,
		jwtSecret:       jwtSecret,
		guestThreads:    guestThreads,
		rpmPerThread:    rpmPerThread,
		debugEnabled:    debugEnabled,
		requireVerified: requireVerified,
		limiters:        map[string]*limiterEntry{},
	}
}

// AuthenticateScrape resolves the two credential layers into a scrape subject.
// Developer app credentials are always required; the user credential is
// optional and falls back to guest mode. It also applies the per-minute rate
// limit for the resolved subject.
func (s *ScrapeService) AuthenticateScrape(ctx context.Context, creds auth.ScrapeCredentials) (*auth.ScrapeSubject, error) {
	if creds.ClientID == "" || creds.ClientSecret == "" {
		return nil, &auth.AuthError{
			Status:  http.StatusUnauthorized,
			Message: "missing developer credentials (X-Client-Id, X-Client-Secret)",
		}
	}

	app, err := s.repo.GetDeveloperAppByClientID(creds.ClientID)
	if err != nil {
		return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid developer credentials"}
	}
	if app.RevokedAt != nil {
		return nil, &auth.AuthError{Status: http.StatusForbidden, Message: "developer application revoked"}
	}
	if !auth.CheckTokenHash(creds.ClientSecret, app.SecretHash) {
		return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid developer credentials"}
	}
	// Avoid a write on every request: only refresh last_used_at when stale.
	if app.LastUsedAt == nil || time.Since(*app.LastUsedAt) > time.Minute {
		_ = s.repo.TouchDeveloperAppLastUsed(creds.ClientID)
	}

	// Enforce a generous per-app rate limit before resolving the optional user
	// credential, so a garbage user credential cannot force an unbounded DB
	// lookup without any throttling. The real per-subject limit is applied below.
	if !s.limiterFor("pre:"+app.ClientID, s.preCheckRPM()).Allow() {
		s.record(app.ID, resolveSoftwareName(creds.SoftwareName, app.Name), "rate_limited")
		return nil, &auth.AuthError{Status: http.StatusTooManyRequests, Message: "rate limit exceeded"}
	}

	subject := &auth.ScrapeSubject{
		Kind:          auth.ScrapeKindGuest,
		ClientID:      app.ClientID,
		ClientDBID:    app.ID,
		ClientName:    app.Name,
		ClientOwnerID: app.UserID,
		SoftwareName:  resolveSoftwareName(creds.SoftwareName, app.Name),
		Threads:       s.guestThreads,
		DailyLimit:    s.guestThreads * repository.DailyGamesPerThread,
	}

	if creds.UserCredential != "" {
		user, err := s.resolveUser(creds.UserCredential)
		if err != nil {
			return nil, err
		}
		threads := repository.ThreadsForUser(user.Role, user.DonorStatus, user.XP)
		subject.Kind = auth.ScrapeKindUser
		subject.UserID = user.ID
		subject.Username = user.Username
		subject.Threads = threads
		subject.DailyLimit = threads * repository.DailyGamesPerThread
	}

	// Developer debug mode: a valid debug password unlocks counter/limit
	// overrides, capped per day. It is gated by ENABLE_DEBUG_MODE and never
	// bypasses authentication.
	if s.debugEnabled && creds.DebugPassword != "" {
		if app.DebugPassword == "" || !auth.CheckTokenHash(creds.DebugPassword, app.DebugPassword) {
			return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid debug password"}
		}
		log.Warn().Str("app", app.ClientID).Msg("scrape debug mode used")
		used, err := s.repo.IncrementDebugUsage(utcDay(), app.ID)
		if err != nil {
			return nil, &auth.AuthError{Status: http.StatusInternalServerError, Message: "debug mode unavailable"}
		}
		if used > maxDebugCallsPerDay {
			s.record(app.ID, subject.SoftwareName, "rate_limited")
			return nil, &auth.AuthError{Status: http.StatusTooManyRequests, Message: "debug daily limit exceeded"}
		}
		_ = s.repo.IncrementDebugCalls(app.ID)
		_ = s.repo.RecordSoftwareOutcome(app.ID, subject.SoftwareName, "debug")
		subject.Debug = true
		subject.ForceUsed = creds.ForceUsed
		subject.ForceRateLimit = creds.ForceRateLimit
		if creds.ForceThreads != nil && *creds.ForceThreads > 0 {
			subject.Threads = *creds.ForceThreads
			subject.DailyLimit = *creds.ForceThreads * repository.DailyGamesPerThread
		}
	}

	if subject.Debug && subject.ForceRateLimit {
		s.record(app.ID, subject.SoftwareName, "rate_limited")
		return nil, &auth.AuthError{Status: http.StatusTooManyRequests, Message: "rate limit exceeded (debug)"}
	}
	if !s.allowSubject(subject) {
		s.record(app.ID, subject.SoftwareName, "rate_limited")
		return nil, &auth.AuthError{Status: http.StatusTooManyRequests, Message: "rate limit exceeded"}
	}
	return subject, nil
}

// record persists a scrape outcome for the developer dashboard (per app and per
// software). Failures are logged but never break the request.
func (s *ScrapeService) record(appID uuid.UUID, software, outcome string) {
	if err := s.repo.RecordScrapeOutcome(appID, outcome); err != nil {
		log.Warn().Err(err).Str("outcome", outcome).Msg("failed to record scrape outcome")
	}
	if err := s.repo.RecordSoftwareOutcome(appID, software, outcome); err != nil {
		log.Warn().Err(err).Str("outcome", outcome).Msg("failed to record software outcome")
	}
}

// RecordOutcome exposes outcome recording to handlers.
func (s *ScrapeService) RecordOutcome(subject *auth.ScrapeSubject, outcome string) {
	if subject == nil || subject.ClientDBID == uuid.Nil {
		return
	}
	s.record(subject.ClientDBID, subject.SoftwareName, outcome)
}

// resolveSoftwareName uses the client-supplied softname, falling back to the
// developer app's name. It is trimmed and capped to keep the stats dimension
// bounded.
func resolveSoftwareName(name, fallback string) string {
	name = strings.TrimSpace(name)
	if name == "" {
		name = fallback
	}
	if len(name) > 120 {
		name = name[:120]
	}
	return name
}

// resolveUser validates a user credential, which may be a personal API key or an
// existing user JWT.
func (s *ScrapeService) resolveUser(credential string) (*models.User, error) {
	if strings.HasPrefix(credential, auth.APIKeyPrefix) {
		prefix := credential
		if len(prefix) > auth.APIKeyPrefixLen {
			prefix = prefix[:auth.APIKeyPrefixLen]
		}
		key, err := s.repo.GetUserAPIKeyByPrefix(prefix)
		if err != nil || !auth.CheckTokenHash(credential, key.KeyHash) {
			return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid user API key"}
		}
		if key.LastUsedAt == nil || time.Since(*key.LastUsedAt) > time.Minute {
			_ = s.repo.TouchUserAPIKeyLastUsed(key.ID)
		}
		user, err := s.repo.GetUserByID(key.UserID)
		if err != nil {
			return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid user credential"}
		}
		if s.requireVerified && !user.EmailVerified {
			return nil, &auth.AuthError{Status: http.StatusForbidden, Message: "email not verified"}
		}
		return user, nil
	}

	claims, err := auth.ParseUserToken(s.jwtSecret, credential)
	if err != nil {
		return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid user credential"}
	}
	user, err := s.repo.GetUserByID(claims.UserID)
	if err != nil {
		return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid user credential"}
	}
	if s.requireVerified && !user.EmailVerified {
		return nil, &auth.AuthError{Status: http.StatusForbidden, Message: "email not verified"}
	}
	return user, nil
}

// preCheckRPM is the generous per-app cap applied before the optional user
// credential is resolved, bounding DB lookups from bogus credentials. It uses
// the maximum thread count so it never throttles a legitimate user.
func (s *ScrapeService) preCheckRPM() int {
	return progression.MaxThreads() * s.rpmPerThread
}

// allowSubject applies the per-minute rate limit for the resolved subject:
// registered users are keyed by user id and get threads * rpmPerThread, guests
// are keyed by the developer app and get the guest thread count.
func (s *ScrapeService) allowSubject(subject *auth.ScrapeSubject) bool {
	key := "app:" + subject.ClientID
	if !subject.IsGuest() {
		key = "user:" + subject.UserID.String()
	}
	return s.limiterFor(key, subject.Threads*s.rpmPerThread).Allow()
}

// limiterFor returns (or lazily creates) the token-bucket limiter for a key.
// Idle entries are evicted after 15 minutes so the map stays bounded without
// ever wiping active buckets. A bucket is rebuilt when its rpm changes (e.g. a
// user's thread count changed with XP or a donation).
func (s *ScrapeService) limiterFor(key string, rpm int) *rate.Limiter {
	s.mu.Lock()
	defer s.mu.Unlock()
	if len(s.limiters) > 10000 {
		cutoff := time.Now().Add(-15 * time.Minute)
		for k, e := range s.limiters {
			if e.last.Before(cutoff) {
				delete(s.limiters, k)
			}
		}
	}
	if e, ok := s.limiters[key]; ok {
		e.last = time.Now()
		if e.rpm == rpm {
			return e.lim
		}
	}
	l := rate.NewLimiter(rate.Limit(float64(rpm)/60.0), rpm)
	s.limiters[key] = &limiterEntry{lim: l, rpm: rpm, last: time.Now()}
	return l
}

