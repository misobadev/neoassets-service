// parenTagRegex and bracketTagRegex strip filename tags such as "(USA)" or
// "[!]" before a name search, mirroring how a scraper client names ROMs.
var (
	parenTagRegex   = regexp.MustCompile(`\([^)]*\)`)
	bracketTagRegex = regexp.MustCompile(`\[[^\]]*\]`)
)

// resolveSystems turns the query selector into the list of systems to search.
// Exactly one of SystemID, Family or Group must be set; a family/group expands
// to all its systems (e.g. "arcade" -> every arcade board, "mame-fbneo" -> the
// boards that run on MAME/FBNeo).
func (s *ScrapeService) resolveSystems(ctx context.Context, q models.ScrapeGameQuery) ([]string, error) {
	systemID := strings.TrimSpace(q.SystemID)
	family := strings.TrimSpace(q.Family)
	group := strings.TrimSpace(q.Group)

	set := 0
	for _, v := range []string{systemID, family, group} {
		if v != "" {
			set++
		}
	}
	if set == 0 {
		return nil, apperr.Invalid("system_id, family or group is required")
	}
	if set > 1 {
		return nil, apperr.Invalid("system_id, family and group are mutually exclusive")
	}

	switch {
	case systemID != "":
		sys, err := s.repo.GetMetadataSystem(ctx, systemID)
		if err != nil {
			return nil, fmt.Errorf("unknown system_id %q", systemID)
		}
		// A virtual system owns no games: it resolves to its group (when set) or
		// its family, so the catalog stays free of duplicated games (e.g. "arcade"
		// covers every arcade board).
		if sys.Virtual {
			if g := strings.TrimSpace(sys.Group); g != "" {
				ids, err := s.meta.ListSystemIDsByGroup(ctx, g)
				if err != nil {
					return nil, err
				}
				if len(ids) > 0 {
					return ids, nil
				}
			}
			if f := strings.TrimSpace(sys.Family); f != "" {
				ids, err := s.meta.ListSystemIDsByFamily(ctx, f)
				if err != nil {
					return nil, err
				}
				if len(ids) > 0 {
					return ids, nil
				}
			}
			return nil, fmt.Errorf("virtual system %q aggregates no systems", systemID)
		}
		return []string{systemID}, nil
	case family != "":
		ids, err := s.meta.ListSystemIDsByFamily(ctx, family)
		if err != nil {
			return nil, err
		}
		if len(ids) == 0 {
			return nil, fmt.Errorf("unknown family %q", family)
		}
		return ids, nil
	default:
		ids, err := s.meta.ListSystemIDsByGroup(ctx, group)
		if err != nil {
			return nil, err
		}
		if len(ids) == 0 {
			return nil, fmt.Errorf("unknown group %q", group)
		}
		return ids, nil
	}
}

// FindGames resolves the query into a single game. The lookup is hash-first: a
// ROM hash (scoped to the selected system or family) is tried first, and when it
// does not match and a name is present the search falls back to the name. It
// returns the game (nil when nothing matched) and how it was matched ("hash" or
// "name").
func (s *ScrapeService) FindGames(ctx context.Context, q models.ScrapeGameQuery) (*models.ScrapeGame, string, error) {
	systemIDs, err := s.resolveSystems(ctx, q)
	if err != nil {
		return nil, "", err
	}
	if len(systemIDs) > maxSystemsPerRequest {
		return nil, "", fmt.Errorf("selector expands to too many systems (%d, max %d)", len(systemIDs), maxSystemsPerRequest)
	}

	name := cleanGameName(q.Name)

	hasHash := q.CRC != "" || q.MD5 != "" || q.SHA1 != "" || q.SHA256 != ""
	if hasHash {
		// One query for every system of the selector, in selector order.
		games, err := s.meta.LookupGameInSystems(ctx, q.CRC, q.MD5, q.SHA1, q.SHA256, systemIDs)
		if err != nil {
			return nil, "", err
		}
		if len(games) > 0 {
			// A hash can match several entries (e.g. a base game and its hacks);
			// prefer the official one, and use the name to disambiguate when the
			// client sent both.
			return s.oneGame(ctx, bestMatch(games, name).ID, q), "hash", nil
		}
		// A hash miss with no name to fall back on is a genuine not-found.
		if name == "" {
			return nil, "hash", nil
		}
	}

	if name == "" {
		return nil, "", apperr.Invalid("name is required")
	}
	// One query for every system of the selector (up to maxGamesLimit
	// candidates each) rather than one per system: a family or group lookup is
	// charged a single quota unit, so its database cost shouldn't grow with
	// the number of systems it covers.
	candidates, err := s.meta.SearchGameCandidates(ctx, name, systemIDs, q.Type, maxGamesLimit)
	if err != nil {
		return nil, "", err
	}
	best := bestMatch(candidates, name)
	if best == nil {
		return nil, "name", nil
	}
	// An arcade ROM is named after its set ("arkanoid.zip"). When the set isn't
	// catalogued, a title that merely starts with or contains it is another
	// game (a sequel, "Arkanoid: Revenge of Doh"), so report not found rather
	// than return the wrong metadata.
	if isRomSetQuery(name) && !strongMatch(best, name) && s.isArcadeSystem(ctx, best.SystemID) {
		return nil, "name", nil
	}
	return s.oneGame(ctx, best.ID, q), "name", nil
}

// isRomSetQuery reports whether a cleaned name looks like a ROM set name: a
// single word with no spaces (e.g. "arkanoid", "sf2ce").
func isRomSetQuery(name string) bool {
	n := strings.TrimSpace(name)
	return n != "" && !strings.ContainsAny(n, " \t")
}

// strongMatch reports whether the game matches the query by ROM file, ROM set
// name or exact title, as opposed to a title prefix or substring.
func strongMatch(g *models.Game, query string) bool {
	q := strings.ToLower(strings.TrimSpace(query))
	return hasRomFile(g.RomNames, q) ||
		(g.ShortName != "" && strings.ToLower(strings.TrimSpace(g.ShortName)) == q) ||
		nameScore(g.Name, q) == 1000
}

// isArcadeSystem reports whether the system belongs to the arcade family.
func (s *ScrapeService) isArcadeSystem(ctx context.Context, systemID string) bool {
	if s.repo == nil || systemID == "" {
		return false
	}
	sys, err := s.repo.GetMetadataSystem(ctx, systemID)
	return err == nil && sys.Family == "arcade"
}

// cleanGameName normalizes a filename-style game name so a ROM name matches
// the catalog: it strips the file extension and parenthesized or bracketed tags
// (region, revision, [!], ...) and collapses whitespace.
func cleanGameName(name string) string {
	name = strings.TrimSpace(name)
	if name == "" {
		return ""
	}
	// Bound the length before the search so huge names cannot explode into
	// thousands of LIKE predicates.
	if r := []rune(name); len(r) > maxScrapeNameLen {
		name = string(r[:maxScrapeNameLen])
	}
	// Drop a trailing file extension (e.g. ".sfc", ".zip").
	if i := strings.LastIndex(name, "."); i > 0 {
		ext := name[i+1:]
		if ext != "" && !strings.ContainsAny(ext, " /\\") && len(ext) <= 5 {
			name = name[:i]
		}
	}
	name = parenTagRegex.ReplaceAllString(name, " ")
	name = bracketTagRegex.ReplaceAllString(name, " ")
	return strings.Join(strings.Fields(name), " ")
}

// oneGame loads a game's full detail, maps it to the scrape payload and bumps
// its scrape counter. It returns nil when the game cannot be loaded.
func (s *ScrapeService) oneGame(ctx context.Context, id uuid.UUID, q models.ScrapeGameQuery) *models.ScrapeGame {
	detail, err := s.meta.GetGame(ctx, id, "")
	if err != nil {
		return nil
	}
	out := s.toScrapeGame(ctx, detail, q)
	out.Scrapes = s.bumpScrape(ctx, id)
	return &out
}

// bumpScrape increments the game's scrape counter and returns the new count.
func (s *ScrapeService) bumpScrape(ctx context.Context, gameID uuid.UUID) int64 {
	if s.repo == nil {
		return 0
	}
	n, err := s.repo.IncrementGameScrape(ctx, gameID)
	if err != nil {
		log.Warn().Err(err).Str("game", gameID.String()).Msg("failed to increment game scrape")
		return 0
	}
	return n
}

// bestMatch picks the most relevant game. For a name search a game with a ROM
// file of that name wins outright, then one whose ROM set name is the query
// (an arcade ROM is named after its set, so "asteroid" is Asteroids, not
// Asteroids Deluxe, whose title it also prefixes); otherwise it scores the
// name match (exact first, then prefix, then substring). For a hash lookup
// (empty query) it just prefers base games and higher ratings. It returns nil
// for an empty list.
func bestMatch(games []models.Game, query string) *models.Game {
	if len(games) == 0 {
		return nil
	}
	q := strings.ToLower(strings.TrimSpace(query))
	best := &games[0]
	bestScore := -1
	for i := range games {
		g := &games[i]
		score := typeBonus(g.Type) + g.Rating
		if q != "" {
			score += nameScore(g.Name, q)
			switch {
			case hasRomFile(g.RomNames, q):
				score += romFileScore
			case g.ShortName != "" && strings.ToLower(strings.TrimSpace(g.ShortName)) == q:
				score += romSetScore
			}
		}
		if score > bestScore {
			bestScore = score
			best = g
		}
	}
	return best
}

// romFileScore and romSetScore outrank any title match, a ROM file above a
// set name (some games carry a set name that isn't their ROM's): see
// bestMatch.
const (
	romFileScore = 20000
	romSetScore  = 10000
)

// hasRomFile reports whether one of romNames (lower case) is q with any file
// extension, or q itself.
func hasRomFile(romNames []string, q string) bool {
	for _, rom := range romNames {
		if rom == q || cleanGameName(rom) == q {
			return true
		}
	}
	return false
}

// nameScore ranks how well a game name matches the query.
func nameScore(name, q string) int {
	n := strings.ToLower(strings.TrimSpace(name))
	switch {
	case n == q:
		return 1000
	case strings.HasPrefix(n, q):
		return 500
	case strings.Contains(n, q):
		return 100
	default:
		return 0
	}
}

// typeBonus prefers official/base games over hacks and homebrew.
func typeBonus(t string) int {
	switch t {
	case "base":
		return 20
	case "homebrew":
		return 10
	default:
		return 0
	}
}

// PopularGames returns the most scraped games, optionally scoped to a system.
func (s *ScrapeService) PopularGames(ctx context.Context, systemID string, limit int) ([]models.PopularGame, error) {
	if limit <= 0 {
		limit = defaultPopularLimit
	}
	if limit > maxPopularLimit {
		limit = maxPopularLimit
	}
	systemID = strings.TrimSpace(systemID)
	if systemID != "" {
		if _, err := s.repo.GetMetadataSystem(ctx, systemID); err != nil {
			return nil, fmt.Errorf("unknown system_id %q", systemID)
		}
	}
	return s.repo.ListPopularGames(ctx, systemID, limit)
}

// toScrapeGame maps an internal game detail into the public scraping payload,
// resolving media object keys into public CDN URLs and optionally filtering the
// media kinds. The ROM list is only included when requested (`roms=true`);
// otherwise just the count is returned to keep the payload light.
func (s *ScrapeService) toScrapeGame(ctx context.Context, d *models.GameDetail, q models.ScrapeGameQuery) models.ScrapeGame {
	want := map[string]bool{}
	for _, k := range q.Media {
		if k != "" {
			want[k] = true
		}
	}

	media := make([]models.ScrapeMedia, 0, len(d.Media))
	for _, m := range d.Media {
		if len(want) > 0 && !want[m.Kind] {
			continue
		}
		media = append(media, models.ScrapeMedia{
			Kind:   m.Kind,
			URL:    s.meta.PublicURL(m.ObjectKey),
			Mime:   m.Mime,
			Size:   m.Size,
			Region: m.Region,
		})
	}

	var names []models.ScrapeName
	for _, r := range d.Regions {
		if r.Name != "" {
			names = append(names, models.ScrapeName{Region: r.Region, Name: r.Name})
		}
	}

	out := models.ScrapeGame{
		ID:           d.ID,
		SystemID:     d.SystemID,
		SystemName:   d.SystemName,
		Name:         d.Name,
		Names:        names,
		Region:       d.Region,
		ReleaseYear:  d.ReleaseYear,
		ReleaseMonth: d.ReleaseMonth,
		Publisher:    d.Publisher,
		Developer:    d.Developer,
		Genre:        d.Genre,
		Rating:       d.Rating,
		Type:         d.Type,
		RomCount:     len(d.Roms),
		Media:        media,
		Descriptions: s.descriptionsByLang(ctx, d.Game),
	}

	if len(d.Roms) > 0 {
		out.RomName = d.Roms[0].Name
	}

	if q.IncludeRoms {
		out.Roms = make([]models.ScrapeRom, 0, len(d.Roms))
		for _, r := range d.Roms {
			out.Roms = append(out.Roms, models.ScrapeRom{
				Name: r.Name, Size: r.Size, CRC: r.CRC, MD5: r.MD5,
				SHA1: r.SHA1, SHA256: r.SHA256, Region: r.Region,
			})
		}
	}
	return out
}

// descriptionsByLang builds the per-language description map: the base English
// description plus every enabled language's translation (empty when missing).
func (s *ScrapeService) descriptionsByLang(ctx context.Context, game models.Game) map[string]string {
	out := map[string]string{"en": game.Description}
	if s.repo == nil {
		return out
	}

	langs, err := s.meta.ListLanguages(ctx)
	if err != nil {
		return out
	}
	translations, err := s.repo.GameDescriptionsByLang(ctx, game.ID)
	if err != nil {
		translations = nil
	}
	for _, l := range langs {
		if l.Code == "en" {
			continue
		}
		out[l.Code] = translations[l.Code]
	}
	return out
}

// RecordUsage counts one game lookup in today's per-person usage (shown in the
// account and admin stats; there is no daily limit) and returns today's count.
func (s *ScrapeService) RecordUsage(ctx context.Context, subject *auth.ScrapeSubject) (int, error) {
	subjectType, subjectID := usageKey(subject)
	return s.repo.IncrementScrapeUsage(ctx, utcDay(), subjectType, subjectID)
}

// Account returns the current subject and today's usage. Scraping has no daily
// limit, so the quota is always reported as unlimited.
func (s *ScrapeService) Account(ctx context.Context, subject *auth.ScrapeSubject) (*models.ScrapeAccount, error) {
	subjectType, subjectID := usageKey(subject)
	used, err := s.repo.GetScrapeUsage(ctx, utcDay(), subjectType, subjectID)
	if err != nil {
		return nil, err
	}
	acct := &models.ScrapeAccount{
		Subject:       subject.Kind,
		Client:        models.ScrapeClient{ID: subject.ClientID, Name: subject.ClientName},
		Threads:       subject.Threads,
		RatePerMinute: s.subjectRPM(subject),
		Quota:         unlimitedQuota(used),
	}
	if !subject.IsGuest() {
		acct.User = &models.ScrapeUser{Username: subject.Username, Threads: subject.Threads}
	}
	return acct, nil
}

// usageKey returns the (subject_type, subject_id) pair of the usage table.
// Usage belongs to people, not apps: a user is keyed by their account and a
// guest by their network address.
func usageKey(subject *auth.ScrapeSubject) (string, string) {
	if subject.IsGuest() {
		return "guest", guestKey(subject)
	}
	return "user", subject.UserID.String()
}

// guestKey identifies a guest by a hash of their network address (so raw IPs
// are not stored in scrape_usage), or by the app's owner when the address is
// unknown (never the case behind the HTTP handlers).
func guestKey(subject *auth.ScrapeSubject) string {
	if subject.ClientKey != "" {
		return "addr:" + auth.HashToken(subject.ClientKey)[:32]
	}
	return "owner:" + subject.ClientOwnerID.String()
}

// unlimitedQuota is the quota payload: no daily limit, today's usage and when
// the usage counter restarts.
func unlimitedQuota(used int) models.ScrapeQuota {
	return models.ScrapeQuota{
		Unlimited: true,
		Used:      used,
		ResetsAt:  utcDay().Add(24 * time.Hour),
	}
}

// utcDay returns the current UTC calendar date at midnight.
func utcDay() time.Time {
	now := time.Now().UTC()
	return time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, time.UTC)
}
