// Default scrape limits, overridable from the environment.
const (
	// defaultRPMPerThread is the per-minute request budget granted per scrape
	// thread: the effective RPM is threads * RPMPerThread (guest 2 -> 200,
	// admin 16 -> 1600). Threads already scale the daily quota.
	defaultRPMPerThread = 100

	// maxGamesLimit is how many candidates a name search scans to pick the best
	// single match.
	maxGamesLimit = 25

	defaultPopularLimit = 20
	maxPopularLimit     = 50

	// maxDebugCallsPerDay caps developer debug requests per app per day.
	maxDebugCallsPerDay = 100

	// maxSystemsPerRequest caps how many systems a family/group selector may
	// expand to, bounding the cost of a single request.
	maxSystemsPerRequest = 50

	// maxScrapeNameLen caps the cleaned name sent to the search, bounding the
	// number of LIKE predicates generated by tokenization.
	maxScrapeNameLen = 200
)

// ScrapeService authenticates scraping API consumers, enforces per-minute rate
// limits and the daily scrape quota, and serves the public catalog payloads.
type ScrapeService struct {
	repo      *repository.Repository
	meta      *Service // catalog reads (systems/games) reused from the web service
	jwtSecret string

	guestThreads      int
	rpmPerThread      int
	guestRPMPerThread int
	debugEnabled      bool
	requireVerified   bool

	mu       sync.Mutex
	limiters map[string]*limiterEntry

	// Admission control (scrape_admission.go): per-subject thread slots and
	// the global cap on concurrent game lookups.
	subjectSlots slotPool
	globalSlots  slotPool
	maxInFlight  int
	// guestSlots caps the lookups all guests together hold (guestInFlight).
	guestSlots    slotPool
	guestInFlight int
	// openSlots caps the requests all guests (guestOpenCap) and all users
	// (userOpenCap) may have open; live counts them for the status panel.
	openSlots    slotPool
	guestOpenCap int
	userOpenCap  int
	live         liveStats

	// outcomes counts request outcomes per app and software in memory; they
	// are written in batches, so neither a stream of refused requests nor a
	// busy app's many threads (which all update the same developer_apps and
	// app_software_stats rows) cost a database write per request.
	outcomes outcomeBatch
}

// limiterEntry pairs a token bucket with its last access time so stale entries
// can be evicted instead of resetting the whole map. rpm is kept so a bucket is
// rebuilt when a subject's thread count changes.
type limiterEntry struct {
	lim   *rate.Limiter
	rpm   int
	burst int
	last  time.Time
}

// NewScrapeService creates a ScrapeService. Non-positive values fall back to
// the defaults. The daily quota is per account and scales with the thread count
// (threads * DailyGamesPerThread), so more threads also means a bigger daily
// limit.
func NewScrapeService(repo *repository.Repository, meta *Service, jwtSecret string, guestThreads, rpmPerThread int, debugEnabled, requireVerified bool) *ScrapeService {
	if guestThreads <= 0 {
		guestThreads = repo.Economy().GuestThreads
	}
	if rpmPerThread <= 0 {
		rpmPerThread = defaultRPMPerThread
	}
	s := &ScrapeService{
		repo:            repo,
		meta:            meta,
		jwtSecret:       jwtSecret,
		guestThreads:    guestThreads,
		rpmPerThread:    rpmPerThread,
		debugEnabled:    debugEnabled,
		requireVerified: requireVerified,
		limiters:        map[string]*limiterEntry{},
		maxInFlight:     DefaultScrapeMaxInFlight,
		guestInFlight:   DefaultScrapeGuestMaxInFlight,
		guestOpenCap:    DefaultGuestOpenThreads,
		userOpenCap:     DefaultUserOpenThreads,
	}
	if repo != nil {
		s.guestRPMPerThread = repo.Economy().GuestRPMPerThread
	}
	return s
}

// AuthenticateScrape resolves the two credential layers into a scrape subject.
// Developer app credentials are always required; the user credential is
// optional and falls back to guest mode. It also applies the per-minute rate
// limit for the resolved subject.
func (s *ScrapeService) AuthenticateScrape(ctx context.Context, creds auth.ScrapeCredentials) (*auth.ScrapeSubject, error) {
	if creds.ClientID == "" || creds.ClientSecret == "" {
		return nil, &auth.AuthError{
			Status:  http.StatusUnauthorized,
			Message: "missing developer credentials (X-Client-Id, X-Client-Secret)",
		}
	}

	app, err := s.repo.GetDeveloperAppByClientID(ctx, creds.ClientID)
	if err != nil {
		return nil, credentialLookupError(ctx, err, "invalid developer credentials")
	}
	if app.RevokedAt != nil {
		return nil, &auth.AuthError{Status: http.StatusForbidden, Message: "developer application revoked"}
	}
	if !auth.CheckTokenHash(creds.ClientSecret, app.SecretHash) {
		return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid developer credentials"}
	}
	// Avoid a write on every request: only refresh last_used_at when stale.
	if app.LastUsedAt == nil || time.Since(*app.LastUsedAt) > time.Minute {
		_ = s.repo.TouchDeveloperAppLastUsed(ctx, creds.ClientID)
	}

	// Enforce a generous per-app, per-address rate limit before resolving the
	// optional user credential, so a garbage user credential cannot force an
	// unbounded DB lookup without any throttling. It is keyed by the caller's
	// address too: an app shipped in a frontend is used by many people at
	// once, and their combined traffic must not share one bucket. The real
	// per-subject limit is applied below.
	if ok, wait, _ := take1(s.limiterFor("pre:"+app.ClientID+"|"+creds.ClientKey, s.preCheckRPM(), progression.MaxThreads())); !ok {
		s.record(ctx, app.ID, resolveSoftwareName(creds.SoftwareName, app.Name), app.Name, "rate_limited")
		return nil, &auth.AuthError{Status: http.StatusTooManyRequests, Message: "rate limit exceeded", RetryAfter: wait}
	}

	subject := &auth.ScrapeSubject{
		Kind:          auth.ScrapeKindGuest,
		ClientID:      app.ClientID,
		ClientDBID:    app.ID,
		ClientName:    app.Name,
		ClientOwnerID: app.UserID,
		ClientKey:     creds.ClientKey,
		SoftwareName:  resolveSoftwareName(creds.SoftwareName, app.Name),
		Threads:       s.guestThreads,
	}

	if creds.UserCredential != "" {
		user, err := s.resolveUser(ctx, creds.UserCredential)
		if err != nil {
			return nil, err
		}
		threads := s.repo.Economy().ThreadsForUser(user.Role, user.DonorStatus, user.XP)
		subject.Kind = auth.ScrapeKindUser
		subject.UserID = user.ID
		subject.Username = user.Username
		subject.Threads = threads
	}

	// Developer debug mode: a valid debug password unlocks counter/limit
	// overrides, capped per day. It is gated by ENABLE_DEBUG_MODE and never
	// bypasses authentication.
	if s.debugEnabled && creds.DebugPassword != "" {
		if app.DebugPassword == "" || !auth.CheckTokenHash(creds.DebugPassword, app.DebugPassword) {
			return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid debug password"}
		}
		log.Warn().Str("app", app.ClientID).Msg("scrape debug mode used")
		used, err := s.repo.IncrementDebugUsage(ctx, utcDay(), app.ID)
		if err != nil {
			return nil, &auth.AuthError{Status: http.StatusInternalServerError, Message: "debug mode unavailable"}
		}
		if used > maxDebugCallsPerDay {
			s.record(ctx, app.ID, subject.SoftwareName, app.Name, "rate_limited")
			return nil, &auth.AuthError{Status: http.StatusTooManyRequests, Message: "debug daily limit exceeded"}
		}
		_ = s.repo.IncrementDebugCalls(ctx, app.ID)
		_ = s.repo.RecordSoftwareOutcome(ctx, app.ID, subject.SoftwareName, app.Name, "debug", 1)
		subject.Debug = true
		subject.ForceRateLimit = creds.ForceRateLimit
		if creds.ForceThreads != nil && *creds.ForceThreads > 0 {
			subject.Threads = *creds.ForceThreads
		}
	}

	if subject.Debug && subject.ForceRateLimit {
		s.record(ctx, app.ID, subject.SoftwareName, app.Name, "rate_limited")
		return nil, &auth.AuthError{Status: http.StatusTooManyRequests, Message: "rate limit exceeded (debug)"}
	}
	if ok, wait := s.allowSubjectPaced(ctx, subject); !ok {
		s.record(ctx, app.ID, subject.SoftwareName, app.Name, "rate_limited")
		return nil, &auth.AuthError{
			Status:     http.StatusTooManyRequests,
			Message:    fmt.Sprintf("rate limit exceeded: this account allows %d requests per minute", subject.RateLimit),
			RetryAfter: wait,
		}
	}
	return subject, nil
}

// record counts a scrape outcome for the developer dashboard (per app and per
// software; fallback is the app's name, used when the software name can't get
// its own row). It is only counted here and written by the next batch (see
// FlushOutcomes); write failures are logged but never break a request.
func (s *ScrapeService) record(_ context.Context, appID uuid.UUID, software, fallback, outcome string) {
	s.outcomes.add(appID, software, fallback, outcome)
}

func (s *ScrapeService) write(ctx context.Context, appID uuid.UUID, software, fallback, outcome string, n int64) {
	if err := s.repo.RecordScrapeOutcome(ctx, appID, outcome, n); err != nil {
		log.Warn().Err(err).Str("outcome", outcome).Msg("failed to record scrape outcome")
	}
	if err := s.repo.RecordSoftwareOutcome(ctx, appID, software, fallback, outcome, n); err != nil {
		log.Warn().Err(err).Str("outcome", outcome).Msg("failed to record software outcome")
	}
}

// RecordOutcome exposes outcome recording to handlers.
func (s *ScrapeService) RecordOutcome(ctx context.Context, subject *auth.ScrapeSubject, outcome string) {
	if subject == nil || subject.ClientDBID == uuid.Nil {
		return
	}
	s.record(ctx, subject.ClientDBID, subject.SoftwareName, subject.ClientName, outcome)
}

// outcomeFlushInterval is how often batched outcome counts are written.
const outcomeFlushInterval = 10 * time.Second

// maxPendingSoftwarePerApp caps the distinct software names one app can hold in
// the outcome batch between writes; further names are counted under the app's
// own name.
const maxPendingSoftwarePerApp = 50

type outcomeKey struct {
	app      uuid.UUID
	software string
	outcome  string
}

type outcomeCount struct {
	app                         uuid.UUID
	software, fallback, outcome string
	count                       int64
}

// outcomeBatch counts request outcomes per app, software and outcome until
// they are written. Only authenticated apps reach it, so the apps are bounded
// by the registered ones, the names per app by maxPendingSoftwarePerApp and the
// outcomes by the handful the handlers record.
type outcomeBatch struct {
	mu      sync.Mutex
	pending map[outcomeKey]*outcomeCount
	names   map[uuid.UUID]map[string]bool
}

func (b *outcomeBatch) add(app uuid.UUID, software, fallback, outcome string) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.pending == nil {
		b.pending = map[outcomeKey]*outcomeCount{}
		b.names = map[uuid.UUID]map[string]bool{}
	}
	names := b.names[app]
	if names == nil {
		names = map[string]bool{}
		b.names[app] = names
	}
	if !names[software] {
		if len(names) >= maxPendingSoftwarePerApp {
			software = fallback
		}
		names[software] = true
	}
	k := outcomeKey{app, software, outcome}
	if c, ok := b.pending[k]; ok {
		c.count++
		return
	}
	b.pending[k] = &outcomeCount{app: app, software: software, fallback: fallback, outcome: outcome, count: 1}
}

// drain returns the pending counts and empties the batch.
func (b *outcomeBatch) drain() []outcomeCount {
	b.mu.Lock()
	defer b.mu.Unlock()
	out := make([]outcomeCount, 0, len(b.pending))
	for _, c := range b.pending {
		out = append(out, *c)
	}
	b.pending, b.names = nil, nil
	return out
}

// StartOutcomeFlush writes the batched outcome counts every
// outcomeFlushInterval until ctx is done. Call FlushOutcomes once more on
// shutdown so the last counts aren't lost.
func (s *ScrapeService) StartOutcomeFlush(ctx context.Context) {
	go func() {
		ticker := time.NewTicker(outcomeFlushInterval)
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				s.FlushOutcomes(ctx)
			}
		}
	}()
}

// FlushOutcomes writes the batched outcome counts now. Pages that show the
// counters call it first so they never lag behind the batch.
func (s *ScrapeService) FlushOutcomes(ctx context.Context) {
	for _, c := range s.outcomes.drain() {
		s.write(ctx, c.app, c.software, c.fallback, c.outcome, c.count)
	}
}

// maxSoftwareNameBytes caps a software name.
const maxSoftwareNameBytes = 120

// resolveSoftwareName uses the client-supplied softname, falling back to the
// developer app's name. It is trimmed and capped (on a character boundary, so
// the stored name stays valid UTF-8) to keep the stats dimension bounded.
func resolveSoftwareName(name, fallback string) string {
	name = strings.TrimSpace(name)
	if name == "" {
		name = fallback
	}
	if len(name) > maxSoftwareNameBytes {
		cut := maxSoftwareNameBytes
		for cut > 0 && !utf8.RuneStart(name[cut]) {
			cut--
		}
		name = name[:cut]
	}
	return name
}

// resolveUser validates a user credential, which may be a personal API key or an
// existing user JWT.
func (s *ScrapeService) resolveUser(ctx context.Context, credential string) (*models.User, error) {
	if strings.HasPrefix(credential, auth.APIKeyPrefix) {
		prefix := credential
		if len(prefix) > auth.APIKeyPrefixLen {
			prefix = prefix[:auth.APIKeyPrefixLen]
		}
		key, err := s.repo.GetUserAPIKeyByPrefix(ctx, prefix)
		if err != nil {
			return nil, credentialLookupError(ctx, err, "invalid user API key")
		}
		if !auth.CheckTokenHash(credential, key.KeyHash) {
			return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid user API key"}
		}
		if key.LastUsedAt == nil || time.Since(*key.LastUsedAt) > time.Minute {
			_ = s.repo.TouchUserAPIKeyLastUsed(ctx, key.ID)
		}
		user, err := s.repo.GetUserByID(ctx, key.UserID)
		if err != nil {
			return nil, credentialLookupError(ctx, err, "invalid user credential")
		}
		if s.requireVerified && !user.EmailVerified {
			return nil, &auth.AuthError{Status: http.StatusForbidden, Message: "email not verified"}
		}
		return user, nil
	}

	claims, err := auth.ParseUserToken(s.jwtSecret, credential)
	if err != nil {
		return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid user credential"}
	}
	user, err := s.repo.GetUserByID(ctx, claims.UserID)
	if err != nil {
		return nil, credentialLookupError(ctx, err, "invalid user credential")
	}
	if !userTokenCurrent(claims, user) {
		return nil, &auth.AuthError{Status: http.StatusUnauthorized, Message: "invalid user credential"}
	}
	if s.requireVerified && !user.EmailVerified {
		return nil, &auth.AuthError{Status: http.StatusForbidden, Message: "email not verified"}
	}
	return user, nil
}

// credentialRetryAfter is how long a client is told to wait when a
// credential could not be checked.
const credentialRetryAfter = 2 * time.Second

// credentialLookupError maps a failed credential lookup to the client's
// answer. Only a credential that does not exist is refused with 401 and
// invalid; any other failure (a database error, a timeout, a canceled
// request) is a 503 with Retry-After, so a client never discards a valid
// key because the server could not check it.
func credentialLookupError(ctx context.Context, err error, invalid string) error {
	if errors.Is(err, sql.ErrNoRows) {
		return &auth.AuthError{Status: http.StatusUnauthorized, Message: invalid}
	}
	if ctx.Err() == nil {
		log.Warn().Err(err).Msg("scrape credential lookup failed")
	}
	return &auth.AuthError{
		Status:     http.StatusServiceUnavailable,
		Message:    "credentials could not be checked, retry shortly",
		RetryAfter: credentialRetryAfter,
	}
}

// userTokenCurrent reports whether a user token was issued for the account's
// current token version (a password change or reset revokes older tokens).
func userTokenCurrent(claims *auth.UserClaims, user *models.User) bool {
	return claims.TokenVersion == user.TokenVersion
}

// preCheckRPM is the generous per-app, per-address cap applied before the optional user
// credential is resolved, bounding DB lookups from bogus credentials. It uses
// the maximum thread count so it never throttles a legitimate user.
func (s *ScrapeService) preCheckRPM() int {
	return progression.MaxThreads() * s.rpmPerThread
}

// subjectRPM is a subject's requests per minute: its threads times the
// per-thread rate, which is lower for guests than for registered users.
func (s *ScrapeService) subjectRPM(subject *auth.ScrapeSubject) int {
	if subject.IsGuest() && s.guestRPMPerThread > 0 {
		return subject.Threads * s.guestRPMPerThread
	}
	return subject.Threads * s.rpmPerThread
}

// guestPaceWait is the longest a guest request is held to wait for its rate
// token before it is refused. A guest whose client keeps a steady pace never
// sees a 429: the server simply answers more slowly.
const guestPaceWait = 3 * time.Second

// allowSubjectPaced is allowSubject, except that a guest just over its rate
// (its next token is at most guestPaceWait away) is accepted with a pace
// delay instead of refused: AcquireSubject holds the request that long, while
// it counts as an open thread, before it runs.
func (s *ScrapeService) allowSubjectPaced(_ context.Context, subject *auth.ScrapeSubject) (bool, time.Duration) {
	if !subject.IsGuest() {
		return s.allowSubject(subject)
	}
	subject.PaceDelay, subject.PaceCancel = 0, nil
	rpm := s.subjectRPM(subject)
	lim := s.limiterFor("rpm:"+admissionKey(subject), rpm, subject.Threads)
	subject.RateLimit = rpm
	now := time.Now()
	r := lim.ReserveN(now, 1)
	if !r.OK() {
		return false, time.Minute
	}
	if d := r.DelayFrom(now); d > 0 {
		if d > guestPaceWait {
			r.CancelAt(now)
			return false, d
		}
		subject.PaceDelay = d
		subject.PaceCancel = r.Cancel
	}
	if remaining := int(lim.Tokens()); remaining > 0 {
		subject.RateRemaining = remaining
	}
	return true, 0
}

// allowSubject applies the per-minute rate limit for the resolved subject
// (see subjectRPM), keyed like the threads themselves (the user, or the
// guest's network address). It fills the
// subject's RateLimit/RateRemaining and, when refused, returns how long until
// the next request would be allowed.
func (s *ScrapeService) allowSubject(subject *auth.ScrapeSubject) (bool, time.Duration) {
	rpm := s.subjectRPM(subject)
	ok, wait, remaining := take1(s.limiterFor("rpm:"+admissionKey(subject), rpm, subject.Threads))
	subject.RateLimit = rpm
	subject.RateRemaining = remaining
	return ok, wait
}

// take1 takes one token from lim if one is available now. It never waits: when
// the bucket is empty it returns false and the delay until a token is free.
// remaining is the whole tokens left afterwards.
func take1(lim *rate.Limiter) (ok bool, wait time.Duration, remaining int) {
	now := time.Now()
	r := lim.ReserveN(now, 1)
	if !r.OK() {
		return false, time.Minute, 0
	}
	if d := r.DelayFrom(now); d > 0 {
		r.CancelAt(now)
		return false, d, 0
	}
	remaining = int(lim.TokensAt(now))
	if remaining < 0 {
		remaining = 0
	}
	return true, 0, remaining
}

// rateBurst is how many requests a bucket allows back to back: about five
// seconds of its rate, and never fewer than the threads (a client may fire
// all its threads at once). The full minute is never allowed in one burst.
func rateBurst(rpm, threads int) int {
	b := rpm / 12
	if b < threads {
		b = threads
	}
	if b < 1 {
		b = 1
	}
	return b
}

// limiterFor returns (or lazily creates) the token-bucket limiter for a key.
// Idle entries are evicted after 15 minutes so the map stays bounded without
// ever wiping active buckets. A bucket is rebuilt when its rpm changes (e.g. a
// user's thread count changed with XP or a donation).
func (s *ScrapeService) limiterFor(key string, rpm, threads int) *rate.Limiter {
	s.mu.Lock()
	defer s.mu.Unlock()
	if len(s.limiters) > 10000 {
		cutoff := time.Now().Add(-15 * time.Minute)
		for k, e := range s.limiters {
			if e.last.Before(cutoff) {
				delete(s.limiters, k)
			}
		}
	}
	burst := rateBurst(rpm, threads)
	if e, ok := s.limiters[key]; ok {
		e.last = time.Now()
		if e.rpm == rpm && e.burst == burst {
			return e.lim
		}
	}
	l := rate.NewLimiter(rate.Limit(float64(rpm)/60.0), burst)
	s.limiters[key] = &limiterEntry{lim: l, rpm: rpm, burst: burst, last: time.Now()}
	return l
}

